create or replace function public.add_spot_to_collection(
  p_id_koleksi uuid,
  p_id_spot uuid,
  p_catatan_kurator text default null
)
returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  next_order integer;
  detail_id uuid;
begin
  perform 1
  from public.koleksi
  where id = p_id_koleksi and id_kurator = auth.uid()
  for update;
  if not found then
    raise exception 'Collection not found or not owned by current user';
  end if;

  select coalesce(max(urutan), 0) + 1 into next_order
  from public.detail_koleksi
  where id_koleksi = p_id_koleksi;

  insert into public.detail_koleksi (id_koleksi, id_spot, urutan, catatan_kurator)
  values (p_id_koleksi, p_id_spot, next_order, p_catatan_kurator)
  returning id into detail_id;
  return detail_id;
end;
$$;

create or replace function public.record_story_view(p_id_cerita uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.cerita
  set jumlah_dilihat = jumlah_dilihat + 1
  where id = p_id_cerita
    and kedaluwarsa_pada > now()
    and exists (
      select 1 from public.spots s
      where s.id = public.cerita.id_spot and s.id_status_verifikasi = 2
    );
end;
$$;

create or replace function public.log_activity_from_row()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  actor_id uuid;
  activity_name text;
begin
  if tg_op = 'DELETE' then
    case tg_table_name
      when 'bookmark' then actor_id := old.id_user;
      when 'vote_tips' then actor_id := old.id_user;
      when 'spots' then actor_id := old.id_pembuat;
      when 'media_spot' then actor_id := old.id_pengunggah;
      when 'cerita' then actor_id := old.id_penulis;
      when 'tips_warga' then actor_id := old.id_penulis;
      when 'koleksi' then actor_id := old.id_kurator;
      when 'detail_koleksi' then
        select id_kurator into actor_id from public.koleksi where id = old.id_koleksi;
    end case;
  else
    case tg_table_name
      when 'bookmark' then actor_id := new.id_user;
      when 'vote_tips' then actor_id := new.id_user;
      when 'spots' then actor_id := new.id_pembuat;
      when 'media_spot' then actor_id := new.id_pengunggah;
      when 'cerita' then actor_id := new.id_penulis;
      when 'tips_warga' then actor_id := new.id_penulis;
      when 'koleksi' then actor_id := new.id_kurator;
      when 'detail_koleksi' then
        select id_kurator into actor_id from public.koleksi where id = new.id_koleksi;
    end case;
  end if;

  activity_name := case tg_table_name
    when 'bookmark' then case tg_op when 'INSERT' then 'menyimpan spot' else 'menghapus bookmark spot' end
    when 'vote_tips' then case tg_op when 'INSERT' then 'memberi suara tips' else 'membatalkan suara tips' end
    when 'spots' then 'mengirim spot untuk verifikasi'
    when 'media_spot' then 'mengunggah media spot'
    when 'cerita' then 'membagikan cerita'
    when 'tips_warga' then 'membagikan tips warga'
    when 'koleksi' then 'membuat koleksi'
    when 'detail_koleksi' then case tg_op when 'INSERT' then 'menambahkan spot ke koleksi' else 'menghapus spot dari koleksi' end
    else 'aktivitas'
  end;

  if actor_id is not null then
    insert into public.log_aktivitas (id_user, aktivitas)
    values (actor_id, activity_name);
  end if;

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

