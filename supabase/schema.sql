create table if not exists public.spots (
  id uuid primary key default extensions.gen_random_uuid(),
  id_kecamatan bigint not null references public.kecamatan(id),
  id_kategori bigint not null references public.kategori(id),
  id_pembuat uuid not null references public.users(id),
  id_status_verifikasi bigint not null references public.status_verifikasi(id),
  id_pemverifikasi uuid references public.users(id),
  nama text not null,
  slug text not null unique,
  ringkasan_editorial text not null,
  latitude double precision,
  longitude double precision,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
