create or replace function public.toggle_bookmark(p_id_spot uuid)
returns boolean
language plpgsql
security invoker
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'Authentication required';
  end if;

  delete from public.bookmark
  where id_user = current_user_id and id_spot = p_id_spot;
  if found then
    return false;
  end if;

  insert into public.bookmark (id_user, id_spot)
  values (current_user_id, p_id_spot)
  on conflict (id_user, id_spot) do nothing;
  return true;
end;
$$;

